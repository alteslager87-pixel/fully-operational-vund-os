format binary as 'bin'
org 0x7C00          ; BIOS завжди завантажує перший сектор сюди

start:
    cli             ; Вимикаємо переривання на час налаштування
    xor ax, ax      ; AX = 0
    mov ds, ax      ; Data Segment = 0
    mov es, ax      ; Extra Segment = 0
    mov ss, ax      ; Stack Segment = 0
    mov sp, 0x7C00  ; Стек росте вниз від завантажувача
    sti             ; Вмикаємо переривання

    ; BIOS залишає номер завантажувального диска в регістрі DL.
    ; Зберігаємо його на всяк випадок (хоча зараз він нам не заважає)
    push dx         

    ; Скидаємо контролер диска (Функція 0)
    mov ah, 0x00    
    int 0x13
    jc disk_error   ; Якщо помилка - йдемо в disk_error

    ; Читаємо ядро (core.bin) з диска
    mov ax, 0x1000  ; Завантажимо ядро в сегмент 0x1000
    mov es, ax      ; ES вказує на 0x1000
    xor bx, bx      ; Зсув (offset) = 0. Разом: 0x1000:0x0000

    mov ah, 0x02    ; Функція 2: Читання секторів
    mov al, 15      ; Скільки секторів читати (15 секторів = 7.5 КБ, вистачить для ядра)
    mov ch, 0       ; Циліндр (Cylinder) 0
    mov cl, 2       ; Починаємо з 2-го сектора (1-й сектор - це цей boot.bin)
    mov dh, 0       ; Головка (Head) 0
    ; DL вже містить номер диска (від BIOS)
    int 0x13
    jc disk_error   ; Якщо не прочиталося - помилка

    ; Передаємо управління ЯДРУ (Far Jump)
    jmp 0x1000:0x0000

disk_error:
    ; Якщо диск не прочитався, друкуємо 'E' і зупиняємо систему
    mov ah, 0x0E
    mov al, 'E'
    int 0x10
    cli
    hlt

; Магія завантажувального сектора: заповнюємо нулями до 510 байт
times 510-($-$$) db 0
; Останні 2 байти - сигнатура завантажувального сектора
dw 0xAA55